let selectedModel = '2';
const modelFrame = document.querySelector('#model-frame');
function loadSelectedModel() {
  const model = models[selectedModel];
  modelFrame.title = `${model.name} · OPERA 3D reconstruction`;
  modelFrame.src = `https://sketchfab.com/models/${model.id}/embed?autostart=1`;
  modelFrame.hidden = false;
  document.querySelector('#model-cover').hidden = true;
  document.querySelector('#stop-model').hidden = false;
  document.querySelector('#model-status').textContent = `${model.name} · Drag to rotate; scroll or pinch to zoom. If the viewer is unavailable, use “Open on Sketchfab”.`;
}
document.querySelectorAll('[data-model]').forEach(button => {
  button.addEventListener('click', () => {
    selectedModel = button.dataset.model;
    const model = models[selectedModel];
    document.querySelector('#model-input').src = `static/images/gallery/${selectedModel}.png`;
    document.querySelector('#model-input').alt = `${model.name} input image`;
    document.querySelector('#model-name').textContent = model.name;
    document.querySelector('#model-cover-title').textContent = `Explore ${model.name} in 3D`;
    document.querySelector('#model-link').href = `https://sketchfab.com/3d-models/${model.slug}-${model.id}`;
    document.querySelectorAll('[data-model]').forEach(other => {
      other.classList.toggle('active', other === button);
      other.setAttribute('aria-pressed', String(other === button));
    });
    loadSelectedModel();
  });
});
document.querySelector('#load-model').addEventListener('click', loadSelectedModel);
document.querySelector('#stop-model').addEventListener('click', () => {
  modelFrame.removeAttribute('src');
  modelFrame.hidden = true;
  document.querySelector('#model-cover').hidden = false;
  document.querySelector('#stop-model').hidden = true;
  document.querySelector('#model-status').textContent = 'Viewer unloaded. Select any thumbnail to load its reconstruction.';
});
