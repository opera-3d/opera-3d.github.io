'use strict';
const examples = {
  book: {name: 'Antique book', note: 'Guidance reduces the bulk of the book reconstruction, bringing its proportions closer to the reference.'},
  helmet: {name: 'Helmet', note: 'Compare the helmet silhouette and surface details against the input and ground truth.'},
  bust: {name: 'Marcus bust', note: 'Compare the facial features and draped surface details of this particular bust, beyond its overall category.'},
  axe: {name: 'Axe', note: 'Inspect the proportions of the blade and handle, together with their surface appearance.'},
  sculpture: {name: 'Four-faced sculpture', note: 'Inspect the surface appearance and facial reliefs against the input and ground truth. The same-backbone comparison shows what changes with guidance.'},
  thinker: {name: 'The Thinker', note: 'Inspect the sculptural contours and surface appearance with and without guidance. All panels show the selected reconstructions from the paper.'}
};
document.querySelectorAll('[data-example]').forEach(button => {
  button.addEventListener('click', () => {
    const item = examples[button.dataset.example];
    const comparison = document.querySelector('.comparison');
    const labels = ['input image', 'reconstructed by Era3D', 'reconstructed by Era3D with OPERA', 'ground-truth reference', 'reconstructed by SAM 3D Objects, external reference'];
    comparison.querySelectorAll('img').forEach((image, index) => {
      image.src = `static/images/objects/${button.dataset.example}-${image.dataset.role}.webp`;
      image.alt = `${item.name} ${labels[index]}`;
    });
    document.querySelector('#example-note').textContent = item.note;
    document.querySelectorAll('[data-example]').forEach(other => {
      other.classList.toggle('active', other === button);
      other.setAttribute('aria-pressed', String(other === button));
    });
  });
});
const datasets = {
  omni: {name: 'OmniObject3D', backbone: 'Era3D', width: 3792, height: 4664},
  gso: {name: 'GSO', backbone: 'Wonder3D'},
  objaverse: {name: 'Objaverse', backbone: 'Era3D'}
};
document.querySelectorAll('[data-dataset]').forEach(button => {
  button.addEventListener('click', () => {
    const key = button.dataset.dataset;
    const item = datasets[key];
    const source = `static/images/${key}.png`;
    const description = `${item.name} · ${item.backbone} + combined guidance`;
    const image = document.querySelector('#dataset-image');
    image.src = source;
    image.alt = `Four ${item.name} examples: input followed by six colour views and six normal maps generated by ${item.backbone} with combined guidance.`;
    image.removeAttribute('width'); image.removeAttribute('height');
    document.querySelector('#dataset-zoom').dataset.zoom = source;
    document.querySelector('#dataset-zoom').dataset.description = description;
    document.querySelector('#dataset-caption').textContent = `${description}. Input image at left; generated colour views above their corresponding normal maps. Click the image to inspect details.`;
    document.querySelectorAll('[data-dataset]').forEach(other => {
      other.classList.toggle('active', other === button);
      other.setAttribute('aria-pressed', String(other === button));
    });
  });
});
const dialog = document.querySelector('#lightbox');
document.querySelectorAll('[data-zoom]').forEach(button => {
  button.addEventListener('click', () => {
    document.querySelector('#lightbox-image').src = button.dataset.zoom;
    document.querySelector('#lightbox-image').alt = button.dataset.description;
    document.querySelector('#lightbox-title').textContent = button.dataset.description;
    dialog.showModal();
  });
});
document.querySelector('#close-lightbox').addEventListener('click', () => dialog.close());
dialog.addEventListener('click', event => { if (event.target === dialog) dialog.close(); });

